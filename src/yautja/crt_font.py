"""Portable terminal alphabets with serif, clean and wide raster faces."""
from functools import lru_cache
import io

from PIL import Image, ImageDraw


FAMILIES = {'crt': 'Yautja CRT', 'crt-clean': 'Yautja CRT Clean', 'crt-wide': 'Yautja CRT Wide'}


def face(name):
    if name not in FAMILIES:
        raise ValueError('Unknown CRT face: ' + str(name))
    return {'crt': (SERIF,9,5), 'crt-clean': (CLEAN,10,5), 'crt-wide': (WIDE,7,5)}[name]


@lru_cache(maxsize=512)
def crt_mask(text, height, tracking=0., name='crt'):
    """Render the distinct terminal cells without borrowing Pixel's alphabet."""
    rows, cap, cell_width = face(name)
    height = max(1, round(height))
    cell_height = 6
    advance = 9 * cell_width + max(0, round(tracking * cap * cell_height))
    mask = Image.new('L', (max(1, len(text) * advance), (cap+3) * cell_height))
    draw = ImageDraw.Draw(mask)
    for i, char in enumerate(text):
        for y, row in enumerate(rows.get(char, rows['?'])):
            for x in range(8):
                if row & (1 << (7-x)):
                    left, top = i*advance + x*cell_width, y*cell_height
                    draw.rectangle((left, top, left+cell_width-1, top+cell_height-1), fill=255)
    bounds = mask.getbbox()
    if bounds:
        # Keep advances and whitespace, but normalize vertical ink height just
        # like the other HUD faces. Descenders stay aligned within each line.
        mask = mask.crop((0, bounds[1], max(1, len(text)*advance-cell_width), bounds[3]))
    return mask.resize((max(1, round(mask.width*height/mask.height)), height), Image.Resampling.NEAREST)


@lru_cache(maxsize=3)
def font_data(name='crt'):
    """Compile matching TrueType faces for ImageDraw and other font consumers."""
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    rows, cap, cell_width = face(name)
    unit_x, unit_y = cell_width*10, 60
    glyphs = {'.notdef': TTGlyphPen(None).glyph()}
    cmap = {}
    for code in range(32, 127):
        glyph_name = f'uni{code:04X}'
        pen = TTGlyphPen(None)
        for y, row in enumerate(rows[chr(code)]):
            for x in range(8):
                if row & (1 << (7-x)):
                    left, bottom = x*unit_x, (cap-y-1)*unit_y
                    top = bottom + unit_y
                    pen.moveTo((left,bottom))
                    pen.lineTo((left,top))
                    pen.lineTo((left+unit_x,top))
                    pen.lineTo((left+unit_x,bottom))
                    pen.closePath()
        glyphs[glyph_name] = pen.glyph()
        cmap[code] = glyph_name
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder(list(glyphs))
    builder.setupCharacterMap(cmap)
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({glyph:(9*unit_x,0) for glyph in glyphs})
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupNameTable({'familyName':FAMILIES[name], 'styleName':'Regular',
                            'uniqueFontIdentifier':FAMILIES[name]+'V1'})
    builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
    builder.setupPost()
    builder.font['head'].created = builder.font['head'].modified = 2082844800
    buffer = io.BytesIO()
    builder.save(buffer)
    return buffer.getvalue()

